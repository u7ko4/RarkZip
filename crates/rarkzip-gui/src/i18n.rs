pub fn tr(language: Language, zh: &'static str) -> &'static str {
    if language == Language::Zh {
        return zh;
    }
    if language == Language::En {
        return en(zh);
    }
    if let Some(pack) = pack(language) {
        if let Some((_, value)) = pack.iter().find(|(key, _)| *key == zh) {
            return value;
        }
    }
    en(zh)
}

/// Translate a template containing `{}` placeholders and fill it in order.
pub fn tr_fmt(language: Language, zh: &'static str, args: &[&dyn std::fmt::Display]) -> String {
    let template = tr(language, zh);
    let mut parts = template.split("{}");
    let mut output = String::new();
    if let Some(first) = parts.next() {
        output.push_str(first);
    }
    for (arg, part) in args.iter().zip(parts) {
        output.push_str(&arg.to_string());
        output.push_str(part);
    }
    output
}

